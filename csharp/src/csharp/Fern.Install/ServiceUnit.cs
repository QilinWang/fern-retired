using Fern.Registry;
using System.Text;

namespace Fern.Install;

public union SystemdPathCheck(Accepted<string>, Refused);

/// <summary>
/// Paths are deliberately restricted instead of attempting a second shell or
/// systemd escaping language (Go: SystemdPath in service.go).
/// </summary>
public static class SystemdPath
{
    public static SystemdPathCheck Check(string path)
    {
        if (!System.IO.Path.IsPathRooted(path))
        {
            return new Refused($"systemd unit path \"{path}\" must be absolute");
        }

        foreach (var character in Encoding.UTF8.GetBytes(path))
        {
            if (character is >= (byte)'a' and <= (byte)'z'
                || character is >= (byte)'A' and <= (byte)'Z'
                || character is >= (byte)'0' and <= (byte)'9'
                || character is (byte)'/' or (byte)'.' or (byte)'_' or (byte)'-' or (byte)':')
            {
                continue;
            }

            return new Refused(
                $"systemd unit path \"{path}\" contains characters this installer cannot safely encode; move it under a simple absolute path");
        }

        return new Accepted<string>(path);
    }
}

public sealed record ServiceUnitConfig(
    string SchedulerBinary,
    string Registry,
    string WorkRoot,
    string Receipt,
    ulong CycleSeconds);

public union ServiceUnitRender(Accepted<byte[]>, Refused);

/// <summary>
/// Emits the one systemd route used by the resident scheduler (Go:
/// RenderServiceUnit in service.go). The unit binds the published binary and
/// the exact installation receipt; a hand edit changes its digest and the
/// verifier refuses it.
/// </summary>
public static class ServiceUnit
{
    public static ServiceUnitRender Render(ServiceUnitConfig config)
    {
        if (config.CycleSeconds is < 5 or > 60)
        {
            return new Refused($"scheduler cycle must be 5-60 seconds, got {config.CycleSeconds}");
        }

        foreach (var path in new[] { config.SchedulerBinary, config.Registry, config.WorkRoot, config.Receipt })
        {
            if (SystemdPath.Check(path) is Refused refused)
            {
                return new Refused(refused.Detail);
            }
        }

        var unit =
            "# Generated by the Fern scheduler-service installer; do not hand-edit.\n"
            + "[Unit]\n"
            + $"Description=Fern resident scheduler ({config.Registry})\n"
            + $"ConditionPathExists={config.Registry}\n"
            + $"ConditionPathExists={config.Receipt}\n\n"
            + "[Service]\n"
            + "Type=simple\n"
            // CHG 2026-08-29: was the reviewed workspace. A unit whose working
            // directory is a worktree cannot start once that worktree is gone,
            // which is the dependency this change exists to remove. The work
            // root is the scheduler's own directory and is installed with it.
            + $"WorkingDirectory={config.WorkRoot}\n"
            // CHG 2026-08-28 (caller cutover): `--work-root` left the ExecStart.
            // Go rendered it and Go's serve stored it in ServeConfig without
            // ever reading it, so the flag named a directory no scheduler
            // consulted. The C# serve binary rejects unknown flags, so a dead
            // flag here would be a unit that cannot start. The work root is
            // still checked and created by the installer and still recorded in
            // the installation receipt, which is where it was doing real work.
            + $"ExecStart={config.SchedulerBinary} serve --registry {config.Registry} --installation-receipt {config.Receipt} --cycle-seconds {config.CycleSeconds}\n"
            + "Restart=on-failure\n"
            + "RestartPreventExitStatus=2\n"
            + "RestartSec=5s\n"
            + "KillMode=control-group\n\n"
            + "[Install]\n"
            + "WantedBy=default.target\n";
        return new Accepted<byte[]>(Encoding.UTF8.GetBytes(unit));
    }
}
