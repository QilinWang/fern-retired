using System.CommandLine;
using Fern.Scheduler;

namespace Fern.Run.Cli;

/// <summary>
/// A Site's files checked against its declarations: slice F2 (its read-only
/// half) of docs/programs/2026-09-22-gleam-site-supervision/2026-09-25-how-a-site-is-reached-and-started.
/// The Gleam flow decides; this verb reads files and systemd's state, asks,
/// and prints what the flow found.
/// </summary>
public static class SiteFilesVerbs
{
    public static void Add(Command parent)
    {
        parent.Subcommands.Add(CheckSiteFiles());
        parent.Subcommands.Add(CheckSiteConnection());
        parent.Subcommands.Add(UpdateSiteFiles());
    }

    static Command UpdateSiteFiles()
    {
        var program = new Option<string>("--scheduler-program")
        {
            Description = "Explicit exported Gleam scheduler shipment directory (tools/fern-scheduler-gleam, `gleam export erlang-shipment`).",
            Required = true,
        };
        var profiles = new Option<string?>("--profiles")
        {
            Description = "The directory of execution profiles and supervisor declarations. Default: config/profiles/ of the repository this command is run in.",
        };
        // CHG 2026-09-25 (slice F2, the unit half): with --site, the Site's supervisor unit as well.
        var site = new Option<string?>("--site")
        {
            Description = "Also write this Site's supervisor unit, held from this machine through the maintained SSH helper.",
        };
        var removeExtra = new Option<bool>("--remove-extra")
        {
            Description = "With --site: move the unit's drop-ins into a sibling folder systemd does not read. Without it, "
                        + "drop-ins refuse the unit update, because the rendered unit would refuse to start beside them.",
        };
        var registry = new Option<string?>("--registry")
        {
            Description = "With --site: the Registry Home file the unit's connection check reads to learn whether a "
                        + "supervisor holds the Site's office.",
        };
        var fernRun = new Option<string?>("--fern-run")
        {
            Description = "With --site: the installed fern-run on this machine the unit's checks run, such as "
                        + "runtime/deploy/run-operator-binaries/fern-run.<digest>. Required with --site; a build output or the "
                        + "dotnet host is refused, because a later build or install would change what the unit runs.",
        };
        var helper = new Option<string?>("--helper")
        {
            Description = "With --site: the maintained SSH helper the unit opens its session with. Default: "
                        + "scripts/connect_runpod_ssh.sh of this repository.",
        };
        var command = new Command("update-site-files",
            "Make the Site files match the declarations. The SSH half: every declared Site's SSH entry into "
            + "~/.ssh/fern-sites.config, an Include of it at the top of ~/.ssh/config, and removes a hand-kept block for a "
            + "declared Site only when it sets exactly what the rendered entry sets; it backs ~/.ssh/config up first and "
            + "puts it back if `ssh -G` shows any Site's settings changed. With --site, the unit half: the Site's "
            + "supervisor unit as rendered, with its checks before start, and a systemd reload; it refuses, writing "
            + "nothing, while another unit serving the Site is active. It never starts, stops or restarts a unit.");
        foreach (var option in new Option[] { program, profiles, site, removeExtra, registry, fernRun, helper })
        {
            command.Options.Add(option);
        }
        command.SetAction(parsed =>
        {
            var directory = parsed.GetValue(profiles) ?? RepositoryProfiles();
            if (directory is null)
            {
                Console.Error.WriteLine("update-site-files: not inside the repository; pass --profiles DIR");
                return 3;
            }
            try
            {
                using var scheduler = GleamProgram.FromShipment(parsed.GetValue(program)!);
                var provenance = "Generated by fern-run update-site-files (" + BinaryVersionReport.FromThisBinary().OneLine()
                    + ") from config/profiles/*.supervisor.json and config/profiles/*.json; do not hand-edit.";
                var result = SiteSshFiles.Update(scheduler, SiteFiles.Paths.ForThisUser(directory), new SiteSshFiles.SshG(), provenance);
                foreach (var (site, detail) in result.Refused) Console.Out.WriteLine($"not rendered, Site {site}: {detail}");
                if (!result.Changed && result.Problems.Count == 0)
                {
                    Console.Out.WriteLine("the SSH files already match the declarations");
                }
                if (result.Backup is not null) Console.Out.WriteLine($"backed up ~/.ssh/config to {result.Backup}");
                if (result.IncludeAdded) Console.Out.WriteLine("~/.ssh/config now reads ~/.ssh/fern-sites.config before its first Host block");
                foreach (var alias in result.Removed) Console.Out.WriteLine($"removed the hand-kept Host {alias} block; the rendered entry sets the same options");
                foreach (var (alias, reason) in result.Kept) Console.Out.WriteLine($"kept the hand-kept Host {alias} block: {reason}");
                foreach (var problem in result.Problems) Console.Out.WriteLine(problem);
                if (result.Problems.Count != 0) return 1;
                if (parsed.GetValue(site) is not { } name)
                {
                    Console.Out.WriteLine("no --site: the supervisor units are not written");
                    return 0;
                }
                return UpdateUnit(scheduler, parsed.GetValue(program)!, directory, name, parsed.GetValue(removeExtra),
                    parsed.GetValue(registry), parsed.GetValue(fernRun), parsed.GetValue(helper), provenance);
            }
            catch (GleamProgramException error)
            {
                Console.Error.WriteLine($"update-site-files: the selected Gleam program failed: {error.Message}");
                return 3;
            }
            catch (Exception error) when (error is InvalidOperationException or IOException or UnauthorizedAccessException)
            {
                Console.Error.WriteLine($"update-site-files: {error.Message}");
                return 3;
            }
        });
        return command;
    }

    /// <summary>
    /// The unit half: render, write, move drop-ins aside, reload. The unit's
    /// checks before start are this machine's fern-run running
    /// check-site-files (without counting the unit's own starting state) and
    /// check-site-connection, both against the same shipment and declarations.
    /// </summary>
    static int UpdateUnit(GleamProgram scheduler, string shipment, string profiles, string site, bool removeExtra,
        string? registry, string? fernRun, string? helper, string provenance)
    {
        if (registry is null)
        {
            Console.Error.WriteLine("update-site-files: --site needs --registry, the Home file the unit's connection check "
                                    + "reads; without it the check can never ask through the declared tunnel, and a fresh "
                                    + "start would always be refused");
            return 3;
        }
        var repository = Path.GetDirectoryName(Path.GetFullPath(profiles))!;
        var session = helper ?? Path.Combine(repository, "scripts", "connect_runpod_ssh.sh");
        // CHG 2026-09-25 (the reader's second review): the checks' binary is
        // named, installed and fixed; a build output changes under the unit
        // with every build, and the dotnet host is not fern-run.
        if (fernRun is null)
        {
            Console.Error.WriteLine("update-site-files: --site needs --fern-run, the installed fern-run the unit's checks run "
                                    + "(for example runtime/deploy/run-operator-binaries/fern-run.<digest>)");
            return 3;
        }
        var local = Path.GetFullPath(fernRun);
        // CHG 2026-09-27: an installed fern-run is one under the repository's
        // deploy root; that one test replaces guessing from the path's words
        // (bin/Debug, bin/Release, a file called dotnet).
        var deployRoot = Path.Combine(repository, Fern.Registry.RepositoryLayout.DeployDirectory) + Path.DirectorySeparatorChar;
        if (!File.Exists(local) || !local.StartsWith(deployRoot, StringComparison.Ordinal))
        {
            Console.Error.WriteLine($"update-site-files: --fern-run {local} is not an installed fern-run: the unit's checks run one "
                                    + $"under {deployRoot}, which a build does not replace");
            return 3;
        }
        // systemd's PATH lacks the folder erl is in; the unit carries one that has it.
        var erl = (Environment.GetEnvironmentVariable("PATH") ?? "").Split(':', StringSplitOptions.RemoveEmptyEntries)
            .Select(folder => Path.Combine(folder, "erl")).FirstOrDefault(File.Exists);
        if (erl is null)
        {
            Console.Error.WriteLine("update-site-files: erl is on no folder of this PATH; the unit's checks start the Gleam "
                                    + "program, which needs it");
            return 3;
        }
        var unitPath = string.Join(':', new[] { Path.GetDirectoryName(erl)! }.Concat(SystemdPath).Distinct(StringComparer.Ordinal));
        var home = Path.GetFullPath(registry);
        var fullShipment = Path.GetFullPath(shipment);
        var fullProfiles = Path.GetFullPath(profiles);
        var inputs = new SiteUnitFiles.Inputs(
            unitPath, session, repository,
            [
                [local, "check-site-files", "--scheduler-program", fullShipment, "--profiles", fullProfiles,
                    "--site", site, "--before-start"],
                [local, "check-site-connection", "--scheduler-program", fullShipment, "--profiles", fullProfiles,
                    "--site", site, "--registry", home, "--helper", session],
            ],
            provenance);
        var result = SiteUnitFiles.Update(scheduler, site, SiteFiles.Paths.ForThisUser(profiles),
            new SiteFiles.SystemctlUser().LoadedServices(), inputs, removeExtra, new SiteUnitFiles.SystemctlReload());
        if (result.Refused is { } refused)
        {
            Console.Out.WriteLine($"the unit of Site {site} is not written: {refused}");
            return 1;
        }
        foreach (var (fact, before, after) in result.Changes)
        {
            Console.Out.WriteLine($"changes {fact}: from {before} to {after}");
        }
        Console.Out.WriteLine(result.Written
            ? $"wrote {result.UnitPath} as rendered"
            : $"{result.UnitPath} already matches the rendered unit");
        if (result.MovedTo is { } kept) Console.Out.WriteLine($"what it replaced is kept in {kept}");
        foreach (var moved in result.Moved) Console.Out.WriteLine($"moved the drop-in {moved} into {result.MovedTo}");
        Console.Out.WriteLine(result.Reloaded
            ? "reloaded systemd; nothing was started, stopped or restarted: the unit's next start runs the rendered configuration"
            : "nothing changed, so systemd was not reloaded");
        return 0;
    }

    /// <summary>The PATH the user's systemd manager gives its units, read on this machine on 2026-09-25.</summary>
    static readonly string[] SystemdPath = ["/usr/local/sbin", "/usr/local/bin", "/usr/sbin", "/usr/bin", "/sbin", "/bin"];

    static Command CheckSiteConnection()
    {
        var program = new Option<string>("--scheduler-program")
        {
            Description = "Explicit exported Gleam scheduler shipment directory (tools/fern-scheduler-gleam, `gleam export erlang-shipment`).",
            Required = true,
        };
        var site = new Option<string>("--site") { Description = "The Site to check.", Required = true };
        var profiles = new Option<string?>("--profiles")
        {
            Description = "The directory of execution profiles and supervisor declarations. Default: config/profiles/ of the repository this command is run in.",
        };
        var registry = new Option<string?>("--registry")
        {
            Description = "The Registry Home file, read to learn whether a supervisor holds the Site's office. Without it the "
                        + "check never asks through a tunnel of its own.",
        };
        var fernRun = new Option<string?>("--fern-run")
        {
            Description = "The runtime binary on the Site to look for. Default: the supervisor declaration's fern_run, "
                        + "the one the rendered unit starts.",
        };
        var helper = new Option<string?>("--helper")
        {
            Description = "The maintained SSH helper. Default: scripts/connect_runpod_ssh.sh of this repository.",
        };
        var command = new Command("check-site-connection",
            "Read-only. Whether the Site's SSH address answers, whether the Registry Home answers at the address the Site "
            + "uses for it, and whether the runtime binary is on the Site, in that order; the first that fails is printed "
            + "as one sentence. Asks through a tunnel of its own only when no supervisor holds the Site's office.");
        foreach (var option in new Option[] { program, site, profiles, registry, fernRun, helper }) command.Options.Add(option);
        command.SetAction(parsed =>
        {
            var directory = parsed.GetValue(profiles) ?? RepositoryProfiles();
            var name = parsed.GetValue(site)!;
            if (directory is null)
            {
                Console.Error.WriteLine("check-site-connection: not inside the repository; pass --profiles DIR");
                return 3;
            }
            var profile = Path.Combine(directory, name + ".json");
            var supervisor = Path.Combine(directory, SiteFiles.SupervisorDeclarationName(name));
            if (!File.Exists(profile) || !File.Exists(supervisor))
            {
                Console.Error.WriteLine($"check-site-connection: Site {name} needs {profile} and {supervisor}");
                return 3;
            }
            var helperPath = parsed.GetValue(helper)
                ?? Path.Combine(Path.GetDirectoryName(directory)!, "scripts", "connect_runpod_ssh.sh");
            if (!File.Exists(helperPath))
            {
                Console.Error.WriteLine($"check-site-connection: the maintained SSH helper {helperPath} is missing");
                return 3;
            }
            try
            {
                // CHG 2026-09-25 (slice F2): without --fern-run, the declared binary (the flow reads it).
                var binary = parsed.GetValue(fernRun);
                using var scheduler = GleamProgram.FromShipment(parsed.GetValue(program)!);
                var verdict = SiteConnection.Check(scheduler, File.ReadAllText(profile), File.ReadAllText(supervisor),
                    SiteConnection.Office(parsed.GetValue(registry), name), binary, new SiteConnection.HelperRunner(helperPath));
                Console.Out.WriteLine(verdict.Reached ? $"Site {name}: reached" : $"Site {name}: not reached");
                foreach (var line in verdict.Lines) Console.Out.WriteLine("  " + line);
                return verdict.Reached ? 0 : 1;
            }
            catch (GleamProgramException error)
            {
                Console.Error.WriteLine($"check-site-connection: the selected Gleam program failed: {error.Message}");
                return 3;
            }
            catch (InvalidOperationException error)
            {
                Console.Error.WriteLine($"check-site-connection: {error.Message}");
                return 3;
            }
        });
        return command;
    }

    static Command CheckSiteFiles()
    {
        var program = new Option<string>("--scheduler-program")
        {
            Description = "Explicit exported Gleam scheduler shipment directory (tools/fern-scheduler-gleam, `gleam export erlang-shipment`).",
            Required = true,
        };
        var site = new Option<string?>("--site") { Description = "One Site. Omitted: every Site with a supervisor declaration." };
        var beforeStart = new Option<bool>("--before-start")
        {
            Description = "Run by the Site's unit before it starts: its own starting state is not a finding.",
        };
        var profiles = new Option<string?>("--profiles")
        {
            Description = "The directory of execution profiles and supervisor declarations. Default: config/profiles/ of the repository this command is run in.",
        };
        var command = new Command("check-site-files",
            "Read-only. Check each Site's files — the SSH host entry this machine reaches it by, and the unit that keeps "
            + "its supervisor running with its drop-ins — and every loaded unit that starts a supervisor for it, against "
            + "the Site's execution profile and supervisor declaration. Exit 0 when everything matches, 1 otherwise. "
            + "Opens no SSH connection; writes, starts, stops and reloads nothing.");
        command.Options.Add(program);
        command.Options.Add(site);
        command.Options.Add(profiles);
        command.Options.Add(beforeStart);
        command.SetAction(parsed =>
        {
            var directory = parsed.GetValue(profiles) ?? RepositoryProfiles();
            if (directory is null)
            {
                Console.Error.WriteLine("check-site-files: not inside the repository; pass --profiles DIR");
                return 3;
            }
            var sites = parsed.GetValue(site) is { } one ? [one] : SiteFiles.DeclaredSites(directory);
            if (sites.Count == 0)
            {
                Console.Error.WriteLine($"check-site-files: no supervisor declaration (*.supervisor.json) in {directory}");
                return 1;
            }
            return PrintChecks(parsed.GetValue(program)!, directory, sites, "check-site-files",
                beforeStart: parsed.GetValue(beforeStart));
        });
        return command;
    }

    /// <summary>
    /// Check these Sites and print each one's findings. 0 when every file of
    /// every Site matches, 1 when anything differs, 3 when the check could not
    /// run. Shared by check-site-files and monitor-site.
    /// </summary>
    /// <param name="onlyDeclared">
    /// Check only Sites with a supervisor declaration, and say of the others
    /// that they were not checked, without counting them: monitor-site lists
    /// every registered Site, and most have none yet.
    /// </param>
    internal static int PrintChecks(
        string shipment, string? profiles, IReadOnlyList<string> sites, string verb, bool onlyDeclared = false, bool beforeStart = false)
    {
        var directory = profiles ?? RepositoryProfiles();
        if (directory is null)
        {
            Console.Error.WriteLine($"{verb}: not inside the repository; pass --profiles DIR");
            return 3;
        }
        try
        {
            var loaded = new SiteFiles.SystemctlUser().LoadedServices();
            using var scheduler = GleamProgram.FromShipment(shipment);
            var paths = SiteFiles.Paths.ForThisUser(directory);
            var everythingMatches = true;
            foreach (var name in sites)
            {
                if (onlyDeclared && !File.Exists(Path.Combine(directory, SiteFiles.SupervisorDeclarationName(name))))
                {
                    Console.Out.WriteLine($"Site {name} files: not checked, no supervisor declaration {SiteFiles.SupervisorDeclarationName(name)}");
                    continue;
                }
                var findings = SiteFiles.Check(scheduler, name, paths, loaded, beforeStart);
                var differing = findings.Where(finding => !finding.Matches).ToList();
                everythingMatches &= differing.Count == 0;
                Console.Out.WriteLine(differing.Count == 0
                    ? $"Site {name} files: every file matches its declaration"
                    : $"Site {name} files: {differing.Count} finding(s)");
                foreach (var finding in findings)
                {
                    Console.Out.WriteLine($"  {finding.Kind}: {finding.Sentence}");
                }
            }
            return everythingMatches ? 0 : 1;
        }
        catch (GleamProgramException error)
        {
            Console.Error.WriteLine($"{verb}: the selected Gleam program failed: {error.Message}");
            return 3;
        }
        catch (InvalidOperationException error)
        {
            Console.Error.WriteLine($"{verb}: {error.Message}");
            return 3;
        }
    }

    /// <summary>
    /// The profiles directory of the repository the current directory is in, found by its C# solution.
    /// CHG 2026-09-26: the solution is src/csharp/Fern.sln and the profiles are config/profiles/
    /// (Fern.Registry.RepositoryLayout).
    /// </summary>
    static string? RepositoryProfiles()
    {
        for (var directory = new DirectoryInfo(Directory.GetCurrentDirectory()); directory is not null; directory = directory.Parent)
        {
            if (Fern.Registry.RepositoryLayout.IsRoot(directory.FullName))
            {
                return Path.Combine(directory.FullName, Fern.Registry.RepositoryLayout.ProfilesDirectory);
            }
        }
        return null;
    }
